"""Report generator for the risk management system (P01-T08).

Generates RESIDUAL.md, HEALTH.md and INDEX.md under risk-management/report/
and risk-management/.  All outputs are byte-identical on regeneration.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

_TOOLS_DIR = Path(__file__).resolve().parent
if str(_TOOLS_DIR) not in sys.path:
    sys.path.insert(0, str(_TOOLS_DIR))

import loader  # noqa: E402

_RISK_DIR = Path(__file__).resolve().parents[1]
_REPO_ROOT = Path(__file__).resolve().parents[2]

# Process-health rating limits (Part 6 section 6.20).
_RATING_LIMITS: dict[str, tuple[float, float]] = {
    "attempts_per_task": (1.5, 2.0),
    "repair_share": (0.25, 0.5),
    "stop_interruption": (0.0, 1.0),
    "budget_use": (0.8, 1.0),
    "overhead_share": (0.3, 0.5),
    "open_findings": (3.0, 6.0),
}


def _load_scales(risk_dir: Path) -> dict[str, object]:
    """Load the scales configuration."""
    path = risk_dir / "methodology" / "SCALES.yaml"
    if not path.exists():
        return {}
    with path.open("r", encoding="utf-8") as f:
        data: dict[str, object] = yaml.safe_load(f)
    return data if isinstance(data, dict) else {}


def _threshold(scales: dict[str, object]) -> int:
    """Return the min residual score threshold."""
    rt = scales.get("register_threshold")
    if isinstance(rt, dict):
        val = rt.get("min_residual_score")
        if isinstance(val, int):
            return val
    return 10


def _max_severity(scales: dict[str, object]) -> int:
    """Return the max residual severity requiring acceptance."""
    rt = scales.get("register_threshold")
    if isinstance(rt, dict):
        val = rt.get("max_residual_severity_requiring_acceptance")
        if isinstance(val, int):
            return val
    return 5


def _band_name(score: int) -> str:
    if score <= 4:
        return "low"
    if score <= 9:
        return "medium"
    if score <= 14:
        return "high"
    return "critical"


def _risk_registers(risk_dir: Path) -> list[tuple[str, list[dict[str, object]]]]:
    """Load all risk-type registers."""
    result: list[tuple[str, list[dict[str, object]]]] = []
    for name in ("product-risks", "project-risks", "ai-model-risks", "data-legal-risks"):
        path = risk_dir / "registers" / f"{name}.yaml"
        if path.exists():
            result.append((name, loader.load_register(path)))
    return result


def _all_registers(risk_dir: Path) -> list[tuple[str, list[dict[str, object]]]]:
    """Load all registers (risk, hazard, threat)."""
    result: list[tuple[str, list[dict[str, object]]]] = []
    for name in (
        "product-risks",
        "project-risks",
        "hazards",
        "threats",
        "ai-model-risks",
        "data-legal-risks",
    ):
        path = risk_dir / "registers" / f"{name}.yaml"
        if path.exists():
            result.append((name, loader.load_register(path)))
    return result


def _acceptance_risk_ids(risk_dir: Path) -> set[str]:
    """Load risk ids that have an acceptance record."""
    return loader.load_acceptance_risk_ids(risk_dir)


def generate_residual(risk_dir: Path, repo_root: Path) -> str:
    """Generate RESIDUAL.md content."""
    scales = _load_scales(risk_dir)
    threshold = _threshold(scales)
    max_sev = _max_severity(scales)
    registers = _risk_registers(risk_dir)
    acceptance_ids = _acceptance_risk_ids(risk_dir)

    lines: list[str] = [
        "# Residual Risk Report",
        "",
        "Generated by `risk report` — do not edit by hand.",
        "",
    ]

    # Counts by area.
    area_counts: dict[str, int] = {}
    band_counts: dict[str, int] = {"low": 0, "medium": 0, "high": 0, "critical": 0}
    above_threshold: list[dict[str, object]] = []

    for _name, records in registers:
        for record in records:
            area = str(record.get("area", "unknown"))
            area_counts[area] = area_counts.get(area, 0) + 1
            rl = record.get("residual_likelihood")
            rs = record.get("residual_severity")
            if isinstance(rl, int) and isinstance(rs, int):
                score = rl * rs
                band = _band_name(score)
                band_counts[band] = band_counts.get(band, 0) + 1
                if score >= threshold or rs >= max_sev:
                    rid = str(record.get("id", "?"))
                    accepted = rid in acceptance_ids
                    above_threshold.append(
                        {
                            "id": rid,
                            "area": area,
                            "score": score,
                            "severity": rs,
                            "accepted": accepted,
                        }
                    )

    lines.append("## Counts by area")
    lines.append("")
    lines.append("| area | count |")
    lines.append("|---|---|")
    for area in sorted(area_counts):
        lines.append(f"| {area} | {area_counts[area]} |")
    lines.append("")

    lines.append("## Counts by score band")
    lines.append("")
    lines.append("| band | range | count |")
    lines.append("|---|---|---|")
    for band in ("low", "medium", "high", "critical"):
        ranges = {"low": "1-4", "medium": "5-9", "high": "10-14", "critical": "15-25"}
        lines.append(f"| {band} | {ranges[band]} | {band_counts[band]} |")
    lines.append("")

    lines.append(
        f"## Residual risks above threshold (score >= {threshold} or severity >= {max_sev})"
    )
    lines.append("")
    if above_threshold:
        lines.append("| id | area | score | severity | accepted |")
        lines.append("|---|---|---|---|---|")
        for item in sorted(above_threshold, key=lambda x: str(x["id"])):
            acc = "yes" if item["accepted"] else "no"
            lines.append(
                f"| {item['id']} | {item['area']} | {item['score']} | {item['severity']} | {acc} |"
            )
    else:
        lines.append("None.")
    lines.append("")

    # Controls by lifecycle status.
    controls = loader.load_register(risk_dir / "controls" / "catalogue.yaml")
    lifecycle_counts: dict[str, int] = {"PLANNED": 0, "IMPLEMENTED": 0, "VERIFIED": 0}
    for ctrl in controls:
        status = str(ctrl.get("lifecycle_status", "?"))
        if status in lifecycle_counts:
            lifecycle_counts[status] += 1

    lines.append("## Controls by lifecycle status")
    lines.append("")
    lines.append("| status | count |")
    lines.append("|---|---|")
    for status in ("PLANNED", "IMPLEMENTED", "VERIFIED"):
        lines.append(f"| {status} | {lifecycle_counts[status]} |")
    lines.append("")

    return "\n".join(lines)


def _parse_p00_baseline(repo_root: Path) -> dict[str, object]:
    """Parse the P00 phase report for baseline figures."""
    report_path = repo_root / "docs" / "phase-reports" / "P00.md"
    if not report_path.exists():
        return {}
    text = report_path.read_text(encoding="utf-8")
    tasks = 0
    attempts = 0
    # Count task rows in the attempts table.
    for line in text.splitlines():
        m = re.match(r"\|\s*P00-T(\d+)\s*\|\s*(\d+)\s*\|", line.strip())
        if m:
            tasks += 1
            attempts += int(m.group(2))
    apt = round(attempts / tasks, 2) if tasks else 0
    # Count self-review findings (F1, F2, ...).
    findings = len(re.findall(r"^### F\d+", text, re.MULTILINE))
    # Count fix commits in the commit table.
    fix_commits = len(re.findall(r"\|\s*fix\(", text))
    task_commits = tasks
    repair_share = round(fix_commits / task_commits, 2) if task_commits else 0
    return {
        "tasks": tasks,
        "attempts": attempts,
        "attempts_per_task": apt,
        "repair_share": repair_share,
        "open_findings": findings,
        "stop_interruption": 1,  # F5: first agent run ended at tool-iteration cap
    }


def _rate(measure: str, value: float | None) -> str:
    """Rate a measure: GREEN, AMBER, RED, or NOT_MEASURED."""
    if value is None:
        return "NOT_MEASURED"
    limits = _RATING_LIMITS.get(measure)
    if limits is None:
        return "NOT_MEASURED"
    green, amber = limits
    if value <= green:
        return "GREEN"
    if value <= amber:
        return "AMBER"
    return "RED"


def generate_health(risk_dir: Path, repo_root: Path) -> str:
    """Generate HEALTH.md content."""
    baseline = _parse_p00_baseline(repo_root)

    lines: list[str] = [
        "# Process Health Report",
        "",
        "Generated by `risk report` — do not edit by hand.",
        "",
        "## Process-health table (Part 6 section 6.20)",
        "",
        "| Phase | Tasks | Attempts | Attempts/task | Repair share"
        " | STOP/interrupt | Budget use | Overhead share | Open findings |",
        "|---|---|---|---|---|---|---|---|---|",
    ]

    if baseline:
        apt = baseline.get("attempts_per_task")
        rs = baseline.get("repair_share")
        si = baseline.get("stop_interruption")
        of = baseline.get("open_findings")
        apt_val = float(apt) if isinstance(apt, (int, float)) else None
        rs_val = float(rs) if isinstance(rs, (int, float)) else None
        si_val = float(si) if isinstance(si, (int, float)) else None
        of_val = float(of) if isinstance(of, (int, float)) else None

        apt_str = f"{apt_val:.2f}" if apt_val is not None else "NOT_MEASURED"
        rs_str = f"{rs_val:.2f}" if rs_val is not None else "NOT_MEASURED"
        si_str = f"{int(si_val)}" if si_val is not None else "NOT_MEASURED"
        of_str = f"{int(of_val)}" if of_val is not None else "NOT_MEASURED"

        apt_rate = _rate("attempts_per_task", apt_val)
        rs_rate = _rate("repair_share", rs_val)
        si_rate = _rate("stop_interruption", si_val)
        of_rate = _rate("open_findings", of_val)

        apt_cell = f"{apt_str} ({apt_rate})"
        rs_cell = f"{rs_str} ({rs_rate})"
        si_cell = f"{si_str} ({si_rate})"
        budget_cell = "NOT_MEASURED (NOT_MEASURED)"
        overhead_cell = "NOT_MEASURED (NOT_MEASURED)"
        of_cell = f"{of_str} ({of_rate})"

        lines.append(
            f"| P00 | {baseline.get('tasks', 0)} | {baseline.get('attempts', 0)} | "
            f"{apt_cell} | {rs_cell} | {si_cell} | {budget_cell} | "
            f"{overhead_cell} | {of_cell} |"
        )
    else:
        lines.append(
            "| P00 | NOT_MEASURED | NOT_MEASURED | NOT_MEASURED (NOT_MEASURED) | "
            "NOT_MEASURED (NOT_MEASURED) | NOT_MEASURED (NOT_MEASURED) | "
            "NOT_MEASURED (NOT_MEASURED) | NOT_MEASURED (NOT_MEASURED) | "
            "NOT_MEASURED (NOT_MEASURED) |"
        )

    lines.append("")
    lines.append(
        "Ratings: GREEN, AMBER, RED, NOT_MEASURED. "
        "A measure with no data is NOT_MEASURED and never GREEN."
    )
    lines.append("")

    return "\n".join(lines)


def generate_index(risk_dir: Path) -> str:
    """Generate risk-management INDEX.md content."""
    lines: list[str] = [
        "# Risk Management Index",
        "",
        "Generated by `risk report` — do not edit by hand.",
        "",
        "| File | Records |",
        "|---|---|",
    ]

    for name in (
        "registers/product-risks",
        "registers/project-risks",
        "registers/hazards",
        "registers/threats",
        "registers/ai-model-risks",
        "registers/data-legal-risks",
        "controls/catalogue",
    ):
        path = risk_dir / f"{name}.yaml"
        if path.exists():
            count = len(loader.load_register(path))
            lines.append(f"| {name}.yaml | {count} |")

    for name in ("incidents/LOG", "continuity/DRILLS"):
        path = risk_dir / f"{name}.yaml"
        if path.exists():
            count = len(loader.load_register(path))
            lines.append(f"| {name}.yaml | {count} |")

    lines.append("")
    return "\n".join(lines)


def generate_all(repo_root: Path | None = None) -> int:
    """Generate all report files. Returns 0 on success."""
    if repo_root is None:
        repo_root = _REPO_ROOT
    risk_dir = repo_root / "risk-management"

    report_dir = risk_dir / "report"
    report_dir.mkdir(parents=True, exist_ok=True)

    # RESIDUAL.md
    residual = generate_residual(risk_dir, repo_root)
    (report_dir / "RESIDUAL.md").write_text(residual, encoding="utf-8")

    # HEALTH.md
    health = generate_health(risk_dir, repo_root)
    (report_dir / "HEALTH.md").write_text(health, encoding="utf-8")

    # INDEX.md
    index = generate_index(risk_dir)
    (risk_dir / "INDEX.md").write_text(index, encoding="utf-8")

    return 0
